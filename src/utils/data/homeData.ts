/* ─────────────────────────────────────────────────────────
   HELPER — fetch by slug
   ───────────────────────────────────────────────────────── */
export function getArticleBySlug(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

/* ─────────────────────────────────────────────────────────
   HELPER — related stories (same category, excluding self)
   ───────────────────────────────────────────────────────── */
export function getRelatedStories(slug: string, limit = 4): Article[] {
  const current = getArticleBySlug(slug);
  if (!current) return articles.slice(0, limit);

  const sameCat = articles.filter(
    (a) => a.slug !== slug && a.categorySlug === current.categorySlug,
  );
  const others = articles.filter(
    (a) => a.slug !== slug && a.categorySlug !== current.categorySlug,
  );

  return [...sameCat, ...others].slice(0, limit);
}

